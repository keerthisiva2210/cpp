#include<iostream>
using namespace std;
int main(){
    int length_of_the_hall=12;
    int width_of_the_hall=9;
    int area=length_of_the_hall*width_of_the_hall;
    int perimeter=2*(length_of_the_hall+width_of_the_hall);
    cout<<"Area of the hall: "<<area<<endl;
    cout<<"Perimeter of the hall: "<<perimeter<<endl;
    return 0;
}